#include "spinox/codegen.h"
#include "spinox/il2cpp.h"
#include <cstdio>
#include <string>
namespace spinox::codegen {
static std::string tname(void* type) {
    char* n = spinox::il2cpp::typeNameAlloc(type);
    std::string s = n ? n : "void*";
    spinox::il2cpp::freeString(n);
    if (s == "System.Int32") return "int32_t";
    if (s == "System.Single") return "float";
    if (s == "System.Int64") return "int64_t";
    if (s == "System.Boolean") return "bool";
    if (s == "System.String") return "void*";
    if (s == "System.Void") return "void";
    if (s == "System.Double") return "double";
    if (s == "System.UInt32") return "uint32_t";
    if (s == "System.UInt64") return "uint64_t";
    return "void*";
}
static std::string signature(void* m) {
    std::string sig = tname(spinox::il2cpp::methodReturnType(m)) + " (*)(";
    int argc = spinox::il2cpp::methodArgc(m);
    for (int i = 0; i < argc; i++) {
        sig += tname(spinox::il2cpp::methodParamType(m, i));
        if (i < argc - 1) sig += ", ";
    }
    if (argc == 0) sig += "void";
    return sig + ")";
}
static std::string argsForward(void* m) {
    int argc = spinox::il2cpp::methodArgc(m);
    std::string s;
    for (int i = 0; i < argc; i++) {
        if (!s.empty()) s += ", ";
        s += "a" + std::to_string(i);
    }
    return s.empty() ? "void" : s;
}
static std::string argList(void* m) {
    int argc = spinox::il2cpp::methodArgc(m);
    std::string s;
    for (int i = 0; i < argc; i++) {
        if (!s.empty()) s += ", ";
        s += tname(spinox::il2cpp::methodParamType(m, i)) + " a" + std::to_string(i);
    }
    return s.empty() ? "void" : s;
}
std::string generateLogHook(void* m) {
    const char* name = spinox::il2cpp::methodName(m);
    std::string retT = tname(spinox::il2cpp::methodReturnType(m));
    std::string code;
    code += "// auto-generated by Spinox\n";
    code += "using Fn = " + signature(m) + ";\n";
    code += "static Fn orig = nullptr;\n\n";
    code += "static " + retT + " hook(" + argList(m) + ") {\n";
    code += "    LOGI(\"" + std::string(name) + " called\");\n";
    if (retT == "void") code += "    orig(" + argsForward(m) + ");\n";
    else                code += "    return orig(" + argsForward(m) + ");\n";
    code += "}\n";
    return code;
}
std::string generateReturnHook(void* m, const char* retExpr) {
    const char* name = spinox::il2cpp::methodName(m);
    std::string retT = tname(spinox::il2cpp::methodReturnType(m));
    if (retT == "void") return "// cannot override void method\n";
    std::string code;
    code += "// auto-generated by Spinox — forced return\n";
    code += "using Fn = " + signature(m) + ";\n";
    code += "static Fn orig = nullptr;\n\n";
    code += "static " + retT + " hook(" + argList(m) + ") {\n";
    code += "    return (" + retT + ")(" + retExpr + ");\n";
    code += "}\n";
    return code;
}
std::string generateArgHook(void* m, int idx, const char* newExpr) {
    const char* name = spinox::il2cpp::methodName(m);
    std::string retT = tname(spinox::il2cpp::methodReturnType(m));
    int argc = spinox::il2cpp::methodArgc(m);
    if (idx < 0 || idx >= argc) return "// invalid arg index\n";
    std::string code;
    code += "// auto-generated by Spinox — arg[" + std::to_string(idx) + "]\n";
    code += "using Fn = " + signature(m) + ";\n";
    code += "static Fn orig = nullptr;\n\n";
    code += "static " + retT + " hook(" + argList(m) + ") {\n";
    code += "    a" + std::to_string(idx) + " = (" +
            tname(spinox::il2cpp::methodParamType(m, idx)) + ")(" + newExpr + ");\n";
    if (retT == "void") code += "    orig(" + argsForward(m) + ");\n";
    else                code += "    return orig(" + argsForward(m) + ");\n";
    code += "}\n";
    return code;
}
}
